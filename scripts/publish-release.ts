#!/usr/bin/env bun
/** Signed Ubuntu feed policy. APT generates its own indexes; Tauri owns AppImage updates. */
import { execFileSync, spawnSync } from 'node:child_process';
import { cpSync, existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, renameSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { parseArgs, isDeepStrictEqual } from 'node:util';

export const run = (...args: string[]) => execFileSync(args[0]!, args.slice(1), { encoding: 'utf8' }).trim();
export const digest = (path: string) => new Bun.CryptoHasher('sha256').update(readFileSync(path)).digest('hex');
export function readRelease(directory: string) {
  const manifest = JSON.parse(readFileSync(join(directory, 'release.json'), 'utf8'));
  const { releaseId: id, build, ci, packages } = manifest;
  if (!/^[1-9][0-9]*\.[1-9][0-9]*$/.test(id) || !/^\d+\.\d+\.\d+$/.test(build.version.split('+build.')[0])
    || build.version !== `${build.version.split('+build.')[0]}+build.${id}`) throw Error('Invalid release identity');
  if (build.dirty || !build.packaged || build.target !== 'x86_64-unknown-linux-gnu' || !/^[a-f0-9]{40}$/.test(build.revision)) throw Error('Unsupported build identity');
  if (ci.ref !== 'main' || ci.repository !== 'avoid-quest/couch' || ci.workflow !== 'Package'
    || id !== `${ci.runId}.${ci.attempt}`) throw Error('Only qualified integration builds may be published');
  if (!manifest.qualification.checks.length || !manifest.releaseNotes.trim()) throw Error('Qualification and release notes are required');
  if (packages.length !== 2 || new Set(packages.map((p: { name: string }) => p.name)).size !== 2
    || packages.some((p: { name: string }) => !['couch', 'couch-appliance'].includes(p.name))) throw Error('Both release packages are required');
  for (const p of packages) {
    if (!/^[A-Za-z0-9_.+~-]+\.deb$/.test(p.filename)) throw Error('Invalid package filename');
    const path = join(directory, p.filename);
    if (!lstatSync(path).isFile() || lstatSync(path).size !== p.size || digest(path) !== p.sha256) throw Error('Package digest mismatch');
    const arch = p.name === 'couch' ? 'amd64' : 'all';
    const fields = Object.fromEntries(run('dpkg-deb', '--field', path, 'Package', 'Version', 'Architecture').split('\n').map(line => line.split(': ')));
    if (p.version !== build.version || p.architecture !== arch || fields.Package !== p.name
      || fields.Version !== build.version || fields.Architecture !== arch) throw Error('Debian package identity mismatch');
  }
  return manifest;
}

function publish(artifact: string, root: string, channel: string, key: string) {
  const manifest = readRelease(artifact);
  const id = manifest.releaseId;
  const releases = join(root, 'releases');
  const destination = join(releases, id);
  const history = join(root, '.preview-history');
  for (const directory of [releases, history, join(root, 'dists'), join(root, 'snapshots')]) mkdirSync(directory, { recursive: true });
  if (channel === 'stable' && !existsSync(join(history, id))) throw Error('Stable must promote a previously published Preview artifact');
  if (existsSync(destination)) {
    if (!isDeepStrictEqual(readRelease(destination), manifest)) throw Error('Immutable release metadata differs');
  } else {
    const staging = mkdtempSync(join(releases, '.release-'));
    try {
      for (const name of ['release.json', ...manifest.packages.map((p: { filename: string }) => p.filename)]) cpSync(join(artifact, name), join(staging, name));
      readRelease(staging);
      renameSync(staging, destination);
    } finally { rmSync(staging, { recursive: true, force: true }); }
  }
  const current = join(root, 'dists', channel);
  if (existsSync(current)) {
    const previous = JSON.parse(readFileSync(join(current, 'release.json'), 'utf8'));
    const comparison = spawnSync('dpkg', ['--compare-versions', manifest.build.version, 'lt', previous.build.version]);
    if (comparison.error || ![0, 1].includes(comparison.status!)) throw Error('Could not compare Debian versions');
    if (comparison.status === 0) throw Error('Refusing to move a channel backwards');
    if (previous.releaseId === id && !isDeepStrictEqual(previous, manifest)) throw Error('Existing channel metadata differs');
  }
  const staging = mkdtempSync(join(root, 'snapshots', `${channel}-${id}-`));
  const link = join(root, 'dists', `.${channel}-${process.pid}`);
  let committed = false;
  try {
    const binary = join(staging, 'main/binary-amd64');
    mkdirSync(binary, { recursive: true });
    // Relative package paths are generated by APT, including size and all checksums.
    writeFileSync(join(binary, 'Packages'), execFileSync('apt-ftparchive', ['packages', `releases/${id}`], { cwd: root }));
    const byHash = join(binary, 'by-hash/SHA256');
    if (existsSync(current)) cpSync(join(current, 'main/binary-amd64/by-hash'), join(binary, 'by-hash'), { recursive: true });
    mkdirSync(byHash, { recursive: true });
    cpSync(join(binary, 'Packages'), join(byHash, digest(join(binary, 'Packages'))));
    cpSync(join(destination, 'release.json'), join(staging, 'release.json'));
    const fields = { Origin: 'Couch', Label: 'Couch', Suite: channel, Codename: channel, Architectures: 'amd64', Components: 'main', 'Acquire-By-Hash': 'yes', 'Valid-Until': new Date(Date.now() + 7 * 86400_000).toUTCString(), 'Patterns::': 'release.json' };
    const options = Object.entries(fields).flatMap(([name, value]) => ['-o', `APT::FTPArchive::Release::${name}=${value}`]);
    writeFileSync(join(staging, 'Release'), execFileSync('apt-ftparchive', [...options, 'release', '.'], { cwd: staging }));
    run('gpg', '--batch', '--yes', '--local-user', key, '--digest-algo', 'SHA256', '--clearsign', '--output', join(staging, 'InRelease'), join(staging, 'Release'));
    run('gpg', '--batch', '--verify', join(staging, 'InRelease'));
    symlinkSync(relative(join(root, 'dists'), staging), link);
    renameSync(link, current);
    committed = true;
    if (channel === 'preview') writeFileSync(join(history, id), digest(join(destination, 'release.json')));
  } finally {
    rmSync(link, { force: true });
    if (!committed) rmSync(staging, { recursive: true, force: true });
  }
  console.log(`${channel}: ${id} (${manifest.build.version})`);
}

if (import.meta.main) {
  const { positionals, values } = parseArgs({ args: process.argv.slice(2), allowPositionals: true, options: { key: { type: 'string' }, locked: { type: 'boolean' } } });
  const [artifact, feed, channel] = positionals;
  if (positionals.length !== 3 || !['preview', 'stable'].includes(channel!) || !/^[A-Fa-f0-9]{40,64}$/.test(values.key ?? '')) throw Error('Usage: bun scripts/publish-release.ts ARTIFACT FEED preview|stable --key FINGERPRINT');
  const root = resolve(feed!);
  mkdirSync(root, { recursive: true });
  // util-linux holds the lock across validation, promotion and atomic channel replacement.
  if (!values.locked) {
    const child = spawnSync('flock', [join(root, '.publish.lock'), process.execPath, import.meta.path, ...process.argv.slice(2), '--locked'], { stdio: 'inherit' });
    if (child.error) throw child.error;
    process.exit(child.status ?? 1);
  }
  publish(resolve(artifact!), root, channel!, values.key!);
}
