import { test } from "node:test";
import assert from "node:assert/strict";
import { createTvRemote } from "../src/server/remote";
import type { ServerMessage } from "../src/shared/protocol";

test("TV text capabilities use Core's registry and replies belong to the current TV socket", async () => {
  let current = "tv";
  const sent: ServerMessage[] = [];
  const remote = createTvRemote<string>({ current: socket => socket === current, send: (_, message) => sent.push(message), changed: () => {} });
  const focus = (socket: string, kind: string, token: string) => remote.receive(socket, JSON.stringify({ type: "textFocus", field: { kind, token, value: "", label: "Password", maxLength: 99999, submit: true } }));
  focus("controller", "find", "forged");
  assert.equal(remote.field("tv"), null);
  focus("tv", "device-name", "name");
  assert.deepEqual(remote.field("tv"), { kind: "device-name", token: "name", value: "", label: "Device name", maxLength: 60, submit: true });
  await assert.rejects(remote.text("tv", "name", "x".repeat(61), false), /60/);
  const accepted = remote.text("tv", "name", "Caffè 日本 🍋", true);
  const request = sent.at(-1)!;
  assert.equal(request.type, "text");
  if (request.type !== "text") throw new Error("Expected text relay");
  remote.receive("controller", JSON.stringify({ type: "textResult", requestId: request.requestId, ok: true }));
  current = "replacement";
  remote.receive("tv", JSON.stringify({ type: "textResult", requestId: request.requestId, ok: true }));
  await assert.rejects(accepted, /field changed/);
  focus("replacement", "find", "next");
  const disconnected = remote.text("replacement", "next", "", false);
  remote.close("replacement");
  await assert.rejects(disconnected, /disconnected/);
  focus("replacement", "password", "secret");
  assert.equal(remote.field("replacement"), null);
  remote.close();
});
