import { test } from "node:test";
import assert from "node:assert/strict";
import { access } from "node:fs/promises";
import { join } from "node:path";
import { liveFixture, until } from "./live-input.fixture";
import { decode, ffmpeg, hasFfmpeg, ingests, loads, positions, recording, segment, speaker, start } from "./live-r4.fixture";

const realMedia = { skip: !hasFfmpeg && "Set COUCH_TEST_FFMPEG to a real FFmpeg executable.", timeout: 45_000 };

test("R4 failed RTC and an independent late viewer decode one shared buffered ingest", realMedia, async t => {
  const f = await liveFixture({ media: { ffmpeg, recording: await recording() }, extraDevices: 1 });
  t.after(() => f.close());
  await start(f);
  await until(() => !!f.receiver.load()?.livePeerId);
  f.receiver.report();
  const healthy = await f.connect(2, "&audio=1&video=1");
  assert.equal((await f.publisher.command({ type: "output", deviceId: healthy.id, level: 50, picture: true })).ok, true);
  await until(() => !!healthy.load()?.livePeerId);
  const healthyPeer = healthy.load()!.livePeerId, healthyLoads = loads(healthy).length;
  const playback = f.publisher.state.playback, entry = f.publisher.state.currentEntryId;
  f.receiver.socket.send(JSON.stringify({ type: "liveFailed", peerId: f.receiver.load()!.livePeerId, error: "R4 forced unreachable peer" }));
  await until(() => !!f.receiver.load()?.hls);
  const fallback = f.receiver.load()!;
  assert.equal(fallback.follow, undefined);
  decode((await segment(fallback.source)).bytes, true);
  f.receiver.report();
  const firstLoads = loads(f.receiver).length;
  const late = await f.connect(3, "&audio=1&video=1");
  assert.equal((await f.publisher.command({ type: "output", deviceId: late.id, level: 40, picture: true })).ok, true);
  await until(() => !!late.load()?.livePeerId);
  late.socket.send(JSON.stringify({ type: "liveFailed", peerId: late.load()!.livePeerId, error: "R4 late peer fallback" }));
  await until(() => !!late.load()?.hls);
  const current = await segment(fallback.source), joined = await segment(late.load()!.source);
  decode(joined.bytes, true);
  // The independently authorized links address the same encoded media.
  const sameName = new URL(new URL(current.url).pathname.split("/").at(-1)!, late.load()!.source);
  assert.deepEqual(Buffer.from(await (await fetch(sameName)).arrayBuffer()), current.bytes);
  assert.equal(loads(f.receiver).length, firstLoads, "a late fallback must not reload the existing fallback");
  assert.equal(loads(healthy).length, healthyLoads, "healthy RTC stays on its peer");
  assert.equal(healthy.load()!.livePeerId, healthyPeer);
  assert.equal(f.publisher.state.playback, playback);
  assert.equal(f.publisher.state.currentEntryId, entry);
  assert.equal(ingests(f).length, 1, "fallback viewers share one recorder encoder");
  const owned = ingests(f);
  assert.equal((await f.publisher.command({ type: "endLive", sourceId: "screen" })).ok, true);
  await until(() => f.uploads.size === 0);
  assert.equal((await fetch(fallback.source)).status, 404);
  await f.close();
  for (const encoder of owned) {
    assert.throws(() => process.kill(encoder.pid, 0), { code: "ESRCH" });
    await assert.rejects(access(encoder.cwd));
  }
  t.diagnostic("Real WebM → Hub upload → H264/AAC HLS decoded for two isolated fallback viewers; healthy RTC routing unchanged.");
});

test("R4 split sound/picture and a late picture-only viewer keep the existing audio deadline grid", realMedia, async t => {
  const f = await liveFixture({ media: { ffmpeg, recording: await recording() }, extraDevices: 1 });
  t.after(() => f.close());
  const sound = await speaker(f, 1);
  t.after(() => sound.client.disconnect());
  const clock = await speaker(f, 2);
  t.after(() => clock.client.disconnect());
  await start(f);
  await until(() => !!f.receiver.load());
  f.receiver.report();
  const picture = await f.connect(2, "&audio=1&video=1");
  assert.equal((await f.publisher.command({ type: "output", deviceId: picture.id, level: 0, picture: true })).ok, true);
  assert.equal((await f.publisher.command({ type: "output", deviceId: f.receiver.id, level: 100, picture: false })).ok, true);
  assert.equal((await f.publisher.command({ type: "inSync", inSync: true })).ok, true);
  await until(() => !!picture.load()?.follow && sound.frames.length >= 5);
  const before = loads(picture).length, starts = sound.starts, clears = sound.clears, count = sound.frames.length;
  const first = decode((await segment(picture.load()!.source)).bytes, false);
  assert.ok(sound.frames.some(frame => frame.bytes.some(byte => byte !== 0)), "the remote speaker receives real decoded captured sound");
  const late = await f.connect(3, "&audio=1&video=1");
  assert.equal((await f.publisher.command({ type: "output", deviceId: late.id, level: 0, picture: true })).ok, true);
  await until(() => !!late.load()?.follow && sound.frames.length >= count + 5);
  const lateMedia = await segment(late.load()!.source);
  const latePts = decode(lateMedia.bytes, false);
  const same = await fetch(new URL(new URL(lateMedia.url).pathname.split("/").at(-1)!, picture.load()!.source));
  assert.deepEqual(Buffer.from(await same.arrayBuffer()), lateMedia.bytes);
  assert.equal(loads(picture).length, before, "joining another picture must not recreate the existing renderer");
  assert.equal(sound.starts, starts, "late picture must not restart sound");
  assert.equal(sound.clears, clears, "late picture must not reset the shared clock");
  for (let i = 1; i < sound.frames.length; i++) assert.equal(sound.frames[i]!.timestamp - sound.frames[i - 1]!.timestamp, 100_000);
  assert.deepEqual(late.load()!.follow, picture.load()!.follow);
  assert.ok(latePts.videoPts[0]! >= first.videoPts[0]!, "the late picture joins the present");
  await until(() => positions(clock.metadata).length > 0);
  const point = positions(clock.metadata).at(-1)!;
  assert.ok(Math.abs(point.position - latePts.videoPts[0]!) < 2, "picture metadata and encoded frames must share source PTS");
  assert.equal(ingests(f).length, 1);
  assert.equal(f.encoders().filter(encoder => encoder.args.includes("-f s16le")).length, 1, "split outputs share one source audio decode");
  t.diagnostic(`${sound.frames.length} real encrypted PCM packets; no restart/clear across the independent late picture join.`);
});

test("R4 re-ingest preserves the publication's absolute source timeline and retires old segments", realMedia, async t => {
  const f = await liveFixture({ media: { ffmpeg, recording: await recording() } });
  t.after(() => f.close());
  const sound = await speaker(f, 1);
  t.after(() => sound.client.disconnect());
  const clock = await speaker(f, 2);
  t.after(() => clock.client.disconnect());
  await start(f);
  await until(() => !!f.receiver.load());
  f.receiver.report();
  const picture = await f.connect(2, "&audio=1&video=1");
  assert.equal((await f.publisher.command({ type: "output", deviceId: picture.id, level: 0, picture: true })).ok, true);
  assert.equal((await f.publisher.command({ type: "inSync", inSync: true })).ok, true);
  await until(() => !!picture.load()?.follow && sound.frames.length >= 5);
  const oldLoad = picture.load()!, first = await segment(oldLoad.source, true), firstPts = decode(first.bytes, false).videoPts[0]!;
  const sampledAt = performance.now(), oldIngest = ingests(f)[0]!, playback = f.publisher.state.playback;
  assert.equal((await f.publisher.command({ type: "inSync", inSync: false })).ok, true);
  await until(() => f.uploads.size === 0 && !!picture.load()?.livePeerId);
  // Source capture survives without buffered demand. This is a lifecycle check,
  // not a latency experiment; a new recorder will start its WebM timestamps at 0.
  await new Promise(resolve => setTimeout(resolve, 1500));
  await assert.rejects(access(join(oldIngest.cwd, "av", "stream.m3u8")));
  const loadsBefore = loads(picture).length, framesBefore = sound.frames.length;
  assert.equal((await f.publisher.command({ type: "inSync", inSync: true })).ok, true);
  await until(() => loads(picture).length > loadsBefore && !!picture.load()?.follow && sound.frames.length >= framesBefore + 5);
  const next = await segment(picture.load()!.source, true), nextPts = decode(next.bytes, false).videoPts[0]!;
  const elapsed = (performance.now() - sampledAt) / 1000;
  assert.ok(nextPts > firstPts + 1, `source PTS restarted: ${firstPts}s → ${nextPts}s after ${elapsed.toFixed(2)}s`);
  const captureElapsed = (f.uploadStarts[1]!.at - f.uploadStarts[0]!.at) / 1000;
  assert.ok(Math.abs(nextPts - firstPts - captureElapsed) < 0.25, "absolute PTS must include the publication's time without buffered demand");
  await until(() => (positions(clock.metadata).at(-1)?.position ?? 0) >= nextPts - 0.1);
  const point = positions(clock.metadata).at(-1)!;
  assert.ok(point.position >= nextPts - 0.1, "new sound and picture must use the same continued source clock");
  assert.equal(f.publisher.state.playback, playback);
  assert.equal(ingests(f).length, 2, "demand restart creates exactly one replacement ingest");
  assert.throws(() => process.kill(oldIngest.pid, 0), { code: "ESRCH" });
  t.diagnostic(`Re-ingest picture PTS ${firstPts}s → ${nextPts}s; elapsed fixture wall time ${elapsed.toFixed(2)}s.`);
});
