import { expect, test } from "bun:test";
import { spawnSync } from "node:child_process";

test("mpv loads and replaces one named filter, reports rejection, and excludes live inputs", () => {
  const result = spawnSync(process.execPath, ["-e", `
    import { mock, spyOn } from "bun:test";
    import assert from "node:assert/strict";
    import { EventEmitter } from "node:events";
    const launches = [], messages = [], reports = [], connections = [];
    let lines;
    mock.module("./src/server/helpers.ts", () => ({ helper: async () => "mpv" }));
    spyOn(await import("node:child_process"), "spawn").mockImplementation((path, args) => { launches.push(args); return Object.assign(new EventEmitter(), { kill() {} }); });
    spyOn(await import("node:net"), "connect").mockImplementation(() => { const socket = Object.assign(new EventEmitter(), { write: text => messages.push(JSON.parse(text)), destroy() {} }); connections.push(socket); queueMicrotask(() => socket.emit("connect")); return socket; });
    spyOn(await import("node:readline"), "createInterface").mockImplementation(() => lines = new EventEmitter());
    const { createMpv } = await import("./src/server/mpv.ts");
    const { defaultCompressor } = await import("./src/shared/compressor.ts");
    const player = createMpv(state => reports.push(state));
    const active = { ...defaultCompressor, enabled: true };
    const settle = async () => { for (let i = 0; i < 3; i++) await new Promise(setImmediate); };
    player.send({ type: "load", playbackId: "film", source: "https://example.test/film", compressor: active }); await settle();
    assert.ok(launches.length, JSON.stringify(reports));
    assert.ok(launches[0].some(arg => arg.startsWith("--af=@couch-compressor:lavfi=[acompressor=")));
    assert.ok(messages.some(item => item.command[0] === "af" && item.command[2].includes("link=maximum")));
    const count = messages.length;
    player.send({ type: "compressor", playbackId: "stale", settings: defaultCompressor });
    assert.equal(messages.length, count);
    player.send({ type: "compressor", playbackId: "film", settings: defaultCompressor });
    assert.deepEqual(messages.at(-1).command, ["af", "set", ""]);
    assert.equal(launches.length, 1, "changing settings must not start another mpv");
    lines.emit("line", JSON.stringify({ request_id: 1, error: "error running command" }));
    assert.equal(reports.at(-1).status, "error");
    player.send({ type: "load", playbackId: "live", source: "https://example.test/live", liveSourceId: "capture", compressor: active }); await settle();
    assert.ok(!launches[1].some(arg => arg.startsWith("--af=")));
    const before = messages.length;
    player.send({ type: "compressor", playbackId: "live", settings: active });
    assert.equal(messages.length, before);
    player.close();
  `], { cwd: new URL("../", import.meta.url), encoding: "utf8" });
  expect(result.stderr).toBe(""); expect(result.status).toBe(0);
});
