import { strict as assert } from 'node:assert';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const current = Bun.YAML.parse(await Bun.file('.github/workflows/package.yml').text()) as any;
const baseline = Bun.spawnSync(['git', 'show', 'HEAD:.github/workflows/package.yml']);
assert.equal(baseline.exitCode, 0);
const before = Bun.YAML.parse(baseline.stdout.toString()) as any;
const oldStep = before.jobs.candidate.steps.find((s:any) => s.name === 'Prepare the pinned Debian builder');
const oldBuild = oldStep.run.slice(0, oldStep.run.indexOf('docker create'));
const oldResult = Bun.spawnSync(['bash', '-eu', '-c', 'docker() { printf "%s\\0" "$@"; };\n' + oldBuild]);
assert.equal(oldResult.exitCode, 0, oldResult.stderr.toString());
const oldArgs = oldResult.stdout.toString().split('\0');
const expected = oldArgs.flatMap((arg, i) => arg === '--build-arg' ? [oldArgs[i+1]] : []);
const steps = current.jobs.candidate.steps;
const inputs = steps.find((s:any) => s.id === 'builder-inputs');
const build = steps.find((s:any) => s.name === 'Prepare the pinned Debian builder');
const start = steps.find((s:any) => s.name === 'Start the pinned Debian builder');
const directory = await mkdtemp(join(tmpdir(), 'couch-builder-inputs-'));
try {
  const output = join(directory, 'output');
  const actualResult = Bun.spawnSync(['bash', '-eu', '-c', inputs.run], {env:{...process.env,GITHUB_OUTPUT:output}});
  assert.equal(actualResult.exitCode, 0, actualResult.stderr.toString());
  const outputs = Object.fromEntries((await Bun.file(output).text()).trim().split('\n').map(line=>{const at=line.indexOf('='); return [line.slice(0,at),line.slice(at+1)];}));
  const actual = build.with['build-args'].trim().replace(/\$\{\{ steps\.builder-inputs\.outputs\.([\w-]+) \}\}/g, (_:string,name:string)=>outputs[name]).split('\n');
  assert.deepEqual(actual, expected);
  assert.equal(start.run, oldStep.run.slice(oldStep.run.indexOf('docker create')));
  assert.equal(build.with.context, 'packaging');
  assert.equal(build.with.file, 'packaging/Dockerfile.mac');
  assert.equal(build.with.platforms, 'linux/amd64');
  assert.equal(build.with.tags, 'couch-release-builder');
  assert.equal(build.with.load, true);
  assert.equal(build.with.push, false);
  assert.equal(build.with['cache-from'], 'type=gha,version=2,scope=couch-debian-builder-amd64');
  assert.equal(build.with['cache-to'], 'type=gha,version=2,scope=couch-debian-builder-amd64,mode=min,ignore-error=true');
  for(const step of [inputs,build,start,steps.find((s:any)=>s.uses?.startsWith('docker/setup-buildx-action@'))]) assert.equal(step.if, oldStep.if);
  console.log('PASS: all four evaluated build arguments equal original CLI arguments; container lifecycle is byte-for-byte unchanged; context, platform, load, cache scope and qualification gates match.');
  console.log(JSON.stringify({buildArgs:actual,cacheFrom:build.with['cache-from'],cacheTo:build.with['cache-to']},null,2));
} finally { await rm(directory, {recursive:true,force:true}); }
